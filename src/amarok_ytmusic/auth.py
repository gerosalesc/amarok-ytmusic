"""Web authentication manager for YouTube Music (Browser cookie sync, headers, and OAuth)."""

from __future__ import annotations

import http.cookiejar
import json
import os
import shutil
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ytmusicapi import OAuthCredentials, YTMusic
from ytmusicapi.auth.browser import setup_browser
from ytmusicapi.helpers import get_authorization, initialize_headers

from .config import AppSettings, SettingsStore

YTMUSIC_ORIGIN = "https://music.youtube.com"
DEFAULT_USER_AGENT = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/134.0.0.0 Safari/537.36"
)


@dataclass
class DetectedBrowser:
    id: str
    label: str
    available: bool
    profile_hint: str = ""


class AuthError(RuntimeError):
    """Raised when YouTube Music authentication fails."""


def detect_browsers() -> list[DetectedBrowser]:
    """Detect locally installed Linux browsers that yt-dlp can read cookies from."""
    home = Path.home()
    candidates = [
        ("chrome", "Google Chrome", ["google-chrome", "google-chrome-stable"], [home / ".config/google-chrome"]),
        ("chromium", "Chromium", ["chromium", "chromium-browser"], [home / ".config/chromium"]),
        ("firefox", "Firefox", ["firefox"], [home / ".mozilla/firefox", home / ".var/app/org.mozilla.firefox/.mozilla/firefox"]),
        ("brave", "Brave", ["brave-browser", "brave"], [home / ".config/BraveSoftware/Brave-Browser"]),
        ("vivaldi", "Vivaldi", ["vivaldi", "vivaldi-stable"], [home / ".config/vivaldi"]),
        ("edge", "Microsoft Edge", ["microsoft-edge", "microsoft-edge-stable"], [home / ".config/microsoft-edge"]),
    ]
    found: list[DetectedBrowser] = []
    for bid, label, bins, dirs in candidates:
        existing_dir = next((str(d) for d in dirs if d.exists()), "")
        has_bin = any(shutil.which(b) is not None for b in bins)
        if existing_dir or has_bin:
            found.append(DetectedBrowser(id=bid, label=label, available=bool(existing_dir), profile_hint=existing_dir))
    return found


def cookies_to_netscape(cookies: list[http.cookiejar.Cookie]) -> str:
    """Serialize Cookie objects to a Netscape cookies.txt string for yt-dlp."""
    lines = ["# Netscape HTTP Cookie File", "# Generated by amarok-ytmusic", ""]
    for c in cookies:
        domain = c.domain or ".youtube.com"
        include_subdomains = "TRUE" if domain.startswith(".") else "FALSE"
        path = c.path or "/"
        secure = "TRUE" if c.secure else "FALSE"
        expires = str(int(c.expires)) if c.expires else "0"
        name = c.name
        value = c.value or ""
        lines.append("\t".join([domain, include_subdomains, path, secure, expires, name, value]))
    return "\n".join(lines) + "\n"


def raw_cookie_header_to_netscape(cookie_header: str) -> str:
    """Convert a raw Cookie HTTP header string into a minimal Netscape cookies.txt for yt-dlp."""
    lines = ["# Netscape HTTP Cookie File", "# Generated by amarok-ytmusic", ""]
    far_future = str(int(time.time()) + 365 * 86400)
    for part in cookie_header.split(";"):
        part = part.strip()
        if "=" not in part:
            continue
        name, value = part.split("=", 1)
        name = name.strip()
        value = value.strip()
        if not name:
            continue
        secure = "TRUE" if name.startswith("__Secure-") or name.startswith("__Host-") else "FALSE"
        domain = "music.youtube.com" if name.startswith("__Host-") else ".youtube.com"
        include_subdomains = "FALSE" if name.startswith("__Host-") else "TRUE"
        lines.append("\t".join([domain, include_subdomains, "/", secure, far_future, name, value]))
    return "\n".join(lines) + "\n"


def build_browser_headers_from_cookies(
    cookie_map: dict[str, str],
    authuser: str = "0",
    user_agent: str = DEFAULT_USER_AGENT,
) -> dict[str, str]:
    """Construct a ytmusicapi-compatible browser.json header dict from YouTube cookies."""
    sapisid = cookie_map.get("__Secure-3PAPISID") or cookie_map.get("SAPISID")
    if not sapisid:
        raise AuthError(
            "No YouTube Music session cookie (__Secure-3PAPISID / SAPISID) found. "
            "Please open https://music.youtube.com in your browser, sign in, and try again."
        )

    # ytmusicapi.helpers.sapisid_from_cookie specifically looks up __Secure-3PAPISID
    normalized_cookies = dict(cookie_map)
    if "__Secure-3PAPISID" not in normalized_cookies:
        normalized_cookies["__Secure-3PAPISID"] = sapisid

    cookie_header = "; ".join(f"{k}={v}" for k, v in normalized_cookies.items())
    auth_header = get_authorization(f"{sapisid} {YTMUSIC_ORIGIN}")

    headers: dict[str, str] = {
        "user-agent": user_agent,
        "accept": "*/*",
        "accept-language": "en-US,en;q=0.9",
        "content-type": "application/json",
        "origin": YTMUSIC_ORIGIN,
        "x-origin": YTMUSIC_ORIGIN,
        "x-goog-authuser": str(authuser),
        "cookie": cookie_header,
        "authorization": auth_header,
    }
    headers.update(initialize_headers())
    return headers


def _write_secret_file(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)


class AuthManager:
    """Manages YouTube Music authentication state, browser cookie sync, headers, and OAuth."""

    def __init__(self, store: SettingsStore | None = None) -> None:
        self.store = store or SettingsStore()
        self._pending_oauth: dict[str, Any] | None = None

    def get_settings(self) -> AppSettings:
        return self.store.load()

    def is_authenticated(self) -> bool:
        settings = self.store.load()
        if settings.auth_mode == "browser" and self.store.browser_auth_path.exists():
            return True
        if settings.auth_mode == "oauth" and self.store.oauth_auth_path.exists():
            return True
        return False

    def create_ytmusic(self) -> YTMusic:
        """Create a YTMusic instance using the configured auth (or anonymous fallback)."""
        settings = self.store.load()
        if settings.auth_mode == "browser" and self.store.browser_auth_path.exists():
            return YTMusic(str(self.store.browser_auth_path))
        if (
            settings.auth_mode == "oauth"
            and self.store.oauth_auth_path.exists()
            and settings.oauth_client_id
            and settings.oauth_client_secret
        ):
            creds = OAuthCredentials(
                client_id=settings.oauth_client_id,
                client_secret=settings.oauth_client_secret,
            )
            return YTMusic(str(self.store.oauth_auth_path), oauth_credentials=creds)
        return YTMusic()

    def verify_account(self) -> dict[str, Any]:
        """Verify stored credentials against YouTube Music and return account metadata."""
        if not self.is_authenticated():
            return {"authenticated": False}
        yt = self.create_ytmusic()
        try:
            info = yt.get_account_info()
            return {
                "authenticated": True,
                "accountName": info.get("accountName", "YouTube Music User"),
                "channelHandle": info.get("channelHandle", ""),
                "accountPhotoUrl": info.get("accountPhotoUrl", ""),
            }
        except Exception as exc:
            raise AuthError(f"Saved credentials could not be verified: {exc}") from exc

    def authenticate_from_browser(
        self,
        browser_name: str,
        profile: str | None = None,
        keyring: str | None = None,
        authuser: str = "0",
    ) -> dict[str, Any]:
        """Extract YouTube Music cookies directly from a local browser and save credentials."""
        import yt_dlp.cookies

        browser_key = browser_name.strip().lower()
        if browser_key not in yt_dlp.cookies.SUPPORTED_BROWSERS:
            raise AuthError(f"Unsupported browser: {browser_name}")

        jar = self._extract_browser_jar(browser_key, profile=profile, keyring=keyring)

        yt_cookies: list[http.cookiejar.Cookie] = []
        cookie_map: dict[str, str] = {}
        # Prefer music.youtube.com cookies over generic .youtube.com duplicates
        for c in jar:
            domain = (c.domain or "").lower()
            if domain == "youtube.com" or domain.endswith(".youtube.com"):
                yt_cookies.append(c)
                if c.name not in cookie_map or "music.youtube.com" in domain:
                    cookie_map[c.name] = c.value or ""

        if not yt_cookies:
            raise AuthError(
                f"No youtube.com cookies found in {browser_name}. "
                "Open https://music.youtube.com in that browser, sign in, and click Connect again."
            )

        headers = build_browser_headers_from_cookies(cookie_map, authuser=authuser)
        _write_secret_file(self.store.browser_auth_path, json.dumps(headers, indent=2))
        _write_secret_file(self.store.cookies_txt_path, cookies_to_netscape(yt_cookies))

        settings = self.store.load()
        settings.auth_mode = "browser"
        settings.browser_source = browser_key
        settings.authuser = str(authuser)
        self.store.save(settings)

        return self.verify_account()

    @staticmethod
    def _extract_browser_jar(
        browser_key: str,
        profile: str | None = None,
        keyring: str | None = None,
    ) -> http.cookiejar.CookieJar:
        import yt_dlp.cookies

        if keyring:
            return yt_dlp.cookies.extract_cookies_from_browser(
                browser_key, profile=profile or None, keyring=keyring.upper()
            )

        # On KDE / Linux Mint, Chromium-based browsers may use KWallet, GNOME Keyring, or basictext.
        last_err: Exception | None = None
        if browser_key == "firefox":
            try:
                return yt_dlp.cookies.extract_cookies_from_browser(browser_key, profile=profile or None)
            except Exception as exc:
                raise AuthError(f"Could not read Firefox cookies: {exc}") from exc

        for kr in (None, "KWALLET5", "KWALLET6", "GNOMEKEYRING", "BASICTEXT"):
            try:
                jar = yt_dlp.cookies.extract_cookies_from_browser(
                    browser_key, profile=profile or None, keyring=kr
                )
                # Verify we actually decrypted non-empty cookie values
                has_yt = any(
                    (c.domain or "").lower().endswith("youtube.com") and (c.value or "")
                    for c in jar
                )
                if has_yt:
                    return jar
            except Exception as exc:
                last_err = exc
                continue

        if last_err:
            raise AuthError(
                f"Could not extract cookies from {browser_key} ({last_err}). "
                "You can use the 'Paste Request Headers' tab as an instant fallback."
            ) from last_err
        raise AuthError(
            f"No decrypted YouTube cookies found in {browser_key}. "
            "Make sure you are signed in to https://music.youtube.com, or use 'Paste Request Headers'."
        )

    def authenticate_from_raw_headers(self, raw_headers: str) -> dict[str, Any]:
        """Parse pasted DevTools request headers (standard ytmusicapi browser auth)."""
        if not raw_headers or not raw_headers.strip():
            raise AuthError("Please paste the request headers copied from music.youtube.com.")

        try:
            parsed_json = setup_browser(headers_raw=raw_headers)
            headers = json.loads(parsed_json)
        except Exception as exc:
            raise AuthError(f"Could not parse headers: {exc}") from exc

        cookie_str = headers.get("cookie") or headers.get("Cookie") or ""
        if not cookie_str:
            raise AuthError("Missing 'Cookie' header. Copy the Request Headers from a /browse request on music.youtube.com.")

        # Ensure authorization header is present so ytmusicapi.is_browser() passes
        if "authorization" not in {k.lower() for k in headers}:
            cookie_map: dict[str, str] = {}
            for part in cookie_str.split(";"):
                if "=" in part:
                    k, v = part.strip().split("=", 1)
                    cookie_map[k.strip()] = v.strip()
            sapisid = cookie_map.get("__Secure-3PAPISID") or cookie_map.get("SAPISID")
            if not sapisid:
                raise AuthError("Cookie header does not contain __Secure-3PAPISID or SAPISID. Make sure you are signed in.")
            headers["authorization"] = get_authorization(f"{sapisid} {YTMUSIC_ORIGIN}")

        _write_secret_file(self.store.browser_auth_path, json.dumps(headers, indent=2))
        _write_secret_file(self.store.cookies_txt_path, raw_cookie_header_to_netscape(cookie_str))

        settings = self.store.load()
        settings.auth_mode = "browser"
        settings.browser_source = "headers"
        self.store.save(settings)

        return self.verify_account()

    def start_oauth_device_flow(self, client_id: str, client_secret: str) -> dict[str, Any]:
        """Start Google OAuth TV device-code flow (requires user's Google Cloud TV client credentials)."""
        cid = client_id.strip()
        csec = client_secret.strip()
        if not cid or not csec:
            raise AuthError("Both Google Cloud OAuth Client ID and Client Secret are required.")
        try:
            creds = OAuthCredentials(client_id=cid, client_secret=csec)
            code_resp = creds.get_code()
        except Exception as exc:
            raise AuthError(f"Failed to start Google OAuth device flow: {exc}") from exc

        self._pending_oauth = {
            "client_id": cid,
            "client_secret": csec,
            "device_code": code_resp["device_code"],
            "expires_at": time.time() + int(code_resp.get("expires_in", 1800)),
        }
        return {
            "verification_url": code_resp.get("verification_url", "https://www.google.com/device"),
            "user_code": code_resp["user_code"],
            "expires_in": code_resp.get("expires_in", 1800),
            "interval": code_resp.get("interval", 5),
        }

    def complete_oauth_device_flow(self) -> dict[str, Any]:
        """Exchange the authorized OAuth device code for refresh/access tokens."""
        if not self._pending_oauth:
            raise AuthError("No active OAuth sign-in flow. Start a new device code first.")
        if time.time() > self._pending_oauth["expires_at"]:
            self._pending_oauth = None
            raise AuthError("OAuth device code expired. Please start again.")

        cid = self._pending_oauth["client_id"]
        csec = self._pending_oauth["client_secret"]
        device_code = self._pending_oauth["device_code"]

        try:
            creds = OAuthCredentials(client_id=cid, client_secret=csec)
            raw_token = creds.token_from_code(device_code)
            if "access_token" not in raw_token:
                raise AuthError(
                    raw_token.get("error_description")
                    or raw_token.get("error")
                    or "Authorization is still pending. Complete sign-in in your browser first."
                )
            token_data = dict(raw_token)
            token_data["expires_at"] = int(time.time()) + int(token_data.get("expires_in", 3600))
        except AuthError:
            raise
        except Exception as exc:
            raise AuthError(f"OAuth token exchange failed: {exc}") from exc

        _write_secret_file(self.store.oauth_auth_path, json.dumps(token_data, indent=2))
        settings = self.store.load()
        settings.auth_mode = "oauth"
        settings.browser_source = "oauth"
        settings.oauth_client_id = cid
        settings.oauth_client_secret = csec
        self.store.save(settings)
        self._pending_oauth = None
        return self.verify_account()

    def logout(self) -> None:
        """Remove stored credentials and reset auth state."""
        for p in (self.store.browser_auth_path, self.store.oauth_auth_path, self.store.cookies_txt_path):
            if p.exists():
                p.unlink()
        settings = self.store.load()
        settings.auth_mode = "none"
        settings.browser_source = ""
        self.store.save(settings)
        self._pending_oauth = None
